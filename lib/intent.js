const UNIVERSITY_MENTION = /خوراسگان|دانشگاه\s*آزاد|دانشگاه\s*آزاد\s*اسلامی|دانشگاه\s*(?:اصفهان|ما)|این\s*دانشگاه/;

function matchesAny(text, patterns) {
  return patterns.some(pattern => pattern.test(text));
}

// نوکا مشاور تحصیلی است؛ راهنمایی شغلی فقط وقتی مجاز است که به رشته/تحصیل
// یا انتخاب مسیر دانشگاهی کاربر مربوط باشد. واژه‌های عمومی مثل «برنامه‌نویسی»
// یا «درآمد» به‌تنهایی سؤال را مجاز نمی‌کنند.
const ACADEMIC_SCOPE = [
  /انتخاب\s*رشته|هدایت\s*تحصیلی|مشاوره\s*تحصیلی|راهنمایی\s*تحصیلی|اسم(?:ت)?\s*(?:چیه|چیست)|نامت\s*(?:چیه|چیست)|تو\s*کی\s*هستی/,
  /دانشگاه|دانشکده|دانشجو|دانش\s*آموز|دبیرستان|هنرستان|آموزشیار/,
  /رشته|مقطع|کارشناسی|کاردانی|کارشناسی\s*ارشد|ارشد|دکتری|دکترای|مهندسی/,
  /کنکور|ثبت\s*نام|پذیرش|شهریه|معدل|کارنامه|سوابق(?:\s*تحصیلی)?|امتحانات?|جبران\s*نمره|ترمیم\s*معدل|چارت\s*درسی|واحد\s*درسی|انتخاب\s*واحد|ترم\s*تحصیلی|آزمون\s*ورودی/,
  /روش\s*مطالعه|برنامه\s*ریزی\s*درسی|درس\s*خواندن|امتحان\s*دانشگاه/,
  /کامپیوتر|فناوری\s*اطلاعات|هوش\s*مصنوعی|حقوق|روانشناسی|حسابداری|پرستاری|پزشکی|عمران|معماری|برق|مکانیک|مدیریت|گرافیک|علوم\s*آزمایشگاهی|مامایی|دامپزشکی|زیست\s*شناسی|شیمی/,
  /بازار\s*کار\s*رشته|شغل\s*مرتبط\s*با\s*رشته|مسیر\s*شغلی\s*رشته|آینده\s*شغلی\s*رشته/,
];

const FOLLOW_UP = /^(?:پس|بعدش|اون|این|همین|برای\s*اون|برای\s*این|چطور|چجوری|چقدر|چند|کدوم|کدام|مثال|بیشتر|ادامه|منظورت|یعنی|درسته|چرا|آیا\s*این|چه\s*طور)|(?:ش|شون)\s*(?:چطوره|چیه|چیست|چقدر|چند|کدوم|کدام|لازمه|مناسبه)\s*[؟?]*$/;

function isInCounselingScope(text) {
  return matchesAny(normalize(text), ACADEMIC_SCOPE);
}

function classifyQuestion(question, context = '') {
  const q = normalize(question);
  const ctx = normalize(context);
  // فقط پیام‌های کوتاه/پیگیری می‌توانند حوزه را از سؤال قبلیِ مرتبط به ارث ببرند.
  const followUp = q.length <= 85 && FOLLOW_UP.test(q);
  const scopedText = isInCounselingScope(q)
    ? q
    : (followUp && isInCounselingScope(ctx) ? `${ctx} ${q}` : q);
  const inScope = isInCounselingScope(scopedText);
  if (!inScope) {
    return { mode: 'out_of_scope', general: false, official: false, universityMention: false, inScope: false };
  }

  const general = matchesAny(scopedText, GENERAL);
  const official = matchesAny(scopedText, OFFICIAL);
  const universityMention = UNIVERSITY_MENTION.test(scopedText);

  if ((general && official) || (general && universityMention) || (official && universityMention && general)) {
    return { mode: 'mixed', general, official, universityMention, inScope: true };
  }
  if (official) return { mode: 'university', general, official, universityMention, inScope: true };
  return { mode: 'general', general, official, universityMention, inScope: true };
}

