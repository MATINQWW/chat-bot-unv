// تشخیص نوع درخواست برای انتخاب سیاست پاسخ‌گویی.
// این تشخیص فقط راهنمای Prompt و کنترل کش است؛ جایگزین قضاوت مدل یا منبع رسمی نیست.
function normalize(text) {
  return String(text || '')
    .replace(/[ًٌٍَُِّْ]/g, '')
    .replace(/ي/g, 'ی').replace(/ك/g, 'ک')
    .replace(/[\u200c\u200f]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

const GENERAL = [
  /بازار\s*کار|بازارکار/,
  /مزایا|معایب|نقاط\s*(?:قوت|ضعف)/,
  /آینده\s*(?:شغلی|کاری)|فرصت(?:های)?\s*شغلی|مسیر\s*شغلی/,
  /درآمد|حقوق\s*(?:و\s*)?دستمزد|درآمدزایی/,
  /مهارت|توانایی|استعداد|علاقه(?:مند)?|علاقه\s*دارم/,
  /ریاضی|منطق|برنامه\s*نویسی|کدنویسی|فیزیک/,
  /برای\s*من\s*(?:مناسب|خوب)|به\s*درد\s*من|مناسب\s*(?:من|شخصیت|روحیه)|انتخاب\s*خوبی/,
  /سختی|سخت\s*(?:است|هست|نیست)|چالش(?:های)?|چه\s*چیزهایی\s*یاد/,
  /مقایسه|فرق\s*(?:این|دو|بین)|تفاوت\s*(?:این|دو|بین)/,
  /چه\s*کارهایی\s*می(?:توان|شه)|کجا\s*می(?:توان|شه)\s*(?:کار|استخدام)/,
];

const OFFICIAL = [
  /شهریه|مبلغ|هزینه\s*(?:ثبت\s*نام|ترم|دانشگاه)|پرداخت\s*قسطی|تقسیط/,
  /ظرفیت\s*پذیرش|ظرفیت\s*رشته|مهلت\s*(?:ثبت\s*نام|انتخاب)|تاریخ\s*(?:ثبت\s*نام|انتخاب|شروع)/,
  /شرایط\s*(?:ثبت\s*نام|پذیرش)|مدارک\s*(?:ثبت\s*نام|لازم)|بدون\s*کنکور|سوابق\s*تحصیلی/,
  /آدرس|نشانی|شماره\s*تماس|تلفن|ساعت\s*(?:کاری|اداری)/,
  /شروع\s*کلاس|زمان\s*کلاس|تقویم\s*آموزشی|چارت\s*درسی|تعداد\s*واحد/,
  /(?:رشته|دانشکده).{0,35}(?:دارید|دارد|ارائه\s*می(?:ده|شود)|موجود\s*است)|(?:دارید|دارد|ارائه\s*می(?:ده|شود)).{0,35}(?:رشته|دانشکده)/,
  /(?:خوراسگان|دانشگاه\s*آزاد|دانشگاه\s*(?:اصفهان|ما)).{0,40}(?:دارد|ارائه\s*می|پذیرش|ثبت\s*نام)|(?:دارد|ارائه\s*می|پذیرش).{0,40}(?:خوراسگان|دانشگاه\s*آزاد)/,
  /آزمون\s*(?:ورودی|دکتری|استعداد\s*درخشان)|مصاحبه\s*دکتری|قوانین?\s*(?:پذیرش|ثبت\s*نام)/,
  /وام\s*(?:دانشجویی|شهریه)|آموزشیار|سامانه\s*(?:دانشگاه|ثبت\s*نام)/,
  /ویرایش.{0,25}انتخاب\s*رشته|انتخاب\s*رشته.{0,30}ویرایش|سوابق\s*تحصیلی|تاثیر.{0,20}سوابق|ضریب.{0,15}کنکور|تراز.{0,15}کنکور|ترمیم\s*معدل|امتحانات?\s*(?:جبرانی|نهایی)|جبران\s*نمره|سوابق|کنکور.{0,20}(?:۱۴۰|۱۴۱|140|141)/,
  /لیست\s*رشته|فهرست\s*رشته|رشته\s*های\s*دانشکده|طرح\s*پویش/,
];

const UNIVERSITY_MENTION = /خوراسگان|دانشگاه\s*آزاد|دانشگاه\s*آزاد\s*اسلامی|دانشگاه\s*(?:اصفهان|ما)|این\s*دانشگاه/;

function matchesAny(text, patterns) {
  return patterns.some(pattern => pattern.test(text));
}

function classifyQuestion(question) {
  const q = normalize(question);
  const general = matchesAny(q, GENERAL);
  const official = matchesAny(q, OFFICIAL);
  const universityMention = UNIVERSITY_MENTION.test(q);

  if ((general && official) || (general && universityMention) || (official && universityMention && general)) {
    return { mode: 'mixed', general, official, universityMention };
  }
  if (official) return { mode: 'university', general, official, universityMention };
  // پیش‌فرض در دستیار هدایت تحصیلی: راهنمایی آموزشی عمومی، نه امتناع.
  return { mode: 'general', general, official, universityMention };
}

