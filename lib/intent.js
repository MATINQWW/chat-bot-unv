        'پاسخ را با نتیجه مستقیم شروع کن؛ در صورت تناسب، سپس مزایا، چالش‌ها، مهارت‌های لازم و یک قدم عملی را کوتاه و منظم بیاور. از سلام و مقدمه کلیشه‌ای غیرضروری پرهیز کن.',
        'از آمار دقیق و به‌روز حقوق، نرخ اشتغال، نام کارفرماها یا تضمین استخدام بدون منبع معتبر استفاده نکن. روندها و مسیرهای شغلی عمومی را می‌توانی کیفی توضیح بدهی.',
