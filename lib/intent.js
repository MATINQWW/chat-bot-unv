// تشخیص حوزهٔ مجاز نوکا و سپس نوع درخواست برای انتخاب سیاست پاسخ‌گویی.
// این دروازه در بک‌اند اجرا می‌شود تا پرسش نامرتبط اصلاً به مدل ارسال نشود.
function normalize(text) {
  return String(text || '')
    .replace(/[ًٌٍَُِّْ]/g, '')
    .replace(/ي/g, 'ی').replace(/ك/g, 'ک')
    .replace(/[\u200c\u200f]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

