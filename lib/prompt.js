const REMINDER = 'یادآوری: به حالت پاسخ‌گویی تعیین‌شده توجه کن؛ دانش عمومی را با واقعیت رسمی دانشگاه اشتباه نگیر و هیچ ادعای اختصاصیِ بی‌منبع نساز.';

let LEARNER = null, LEARNER_HASH = null;
function getLearner() {
  const db = load();
  if (LEARNER && LEARNER_HASH === db.hash) return LEARNER;   // دانش عوض شد ⇒ نسخهٔ حافظهٔ یادگیری هم نو می‌شود
  const model = require('./llm').activeModel();
  const ver = crypto.createHash('sha1').update(db.raw + RULES + model).digest('hex').slice(0, 8);
  LEARNER = createLearner(kv, ver, db.chunks.map(c => c.text).join('\n'), { semantic: semCache, entities });
  LEARNER.ver = ver;
  LEARNER_HASH = db.hash;
  return LEARNER;
}

module.exports = { retrieveKnowledge, RULES, REMINDER, getLearner };
