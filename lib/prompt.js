const REMINDER = 'پاسخ را بر اساس شواهد موجود بنویس؛ اطلاعات تأییدنشده را رسمی یا قطعی جلوه نده و منبع ناموجود را جعل نکن.';

let LEARNER = null;
function getLearner() {
  if (LEARNER) return LEARNER;
  const raw = getKnowledgeRaw();
  const model = process.env.ICP_MODEL || 'icp-chat';
  const ver = crypto.createHash('sha1').update(raw + RULES + model).digest('hex').slice(0, 8);
  LEARNER = createLearner(kv, ver, raw);
  LEARNER.ver = ver;
  return LEARNER;
}
module.exports = { retrieveKnowledge, RULES, REMINDER, getLearner };
