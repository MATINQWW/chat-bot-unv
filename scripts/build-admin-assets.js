#!/usr/bin/env node
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const dir = path.join(__dirname, '..', 'lib', 'admin-panel');
const assets = {
  html: fs.readFileSync(path.join(dir, 'index.html'), 'utf8'),
  css: fs.readFileSync(path.join(dir, 'style.css'), 'utf8'),
  js: fs.readFileSync(path.join(dir, 'app.js'), 'utf8'),
};
const out = "'use strict';\n// Generated by scripts/build-admin-assets.js. Do not edit manually.\nmodule.exports = " + JSON.stringify(assets, null, 2) + ";\n";
fs.writeFileSync(path.join(dir, 'assets.js'), out, 'utf8');
console.log('✓ Admin assets bundled.');
